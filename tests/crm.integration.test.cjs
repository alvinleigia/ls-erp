test("enquiries require tenant reasons only on losing; reopening keeps history and requires a new valid choice", async () => {
  const contact = await manager.createContact({ name: "Lost enquiry buyer" })
  let lead = await manager.createEnquiry(enquiryInput(contact.id, staffA.id))
  const reason = await manager.createLostReason({ name: "Invalid contact details" })
  const foreign = await second.createLostReason({ name: "Foreign reason" })
  const update = (extra = {}) => ({ title: lead.title, assignedUserId: staffA.id, status: "CLOSED", version: lead.version, ...extra })
  await assert.rejects(staff.updateEnquiry(lead.id, update({ outcome: "Free text alone is insufficient" })), expectStatus(400))
  await assert.rejects(staff.updateEnquiry(lead.id, update({ lostReasonId: foreign.id })), expectStatus(400))
  await assert.rejects(other.updateEnquiry(lead.id, update({ lostReasonId: reason.id })), expectStatus(404))
  lead = await staff.updateEnquiry(lead.id, update({ lostReasonId: reason.id, outcome: "Phone is disconnected" }))
  assert.equal(lead.lostReasonName, reason.name)
  assert.equal((await staff.listEnquiries({ lostReasonId: reason.id })).total, 1)
  await manager.updateLostReason(reason.id, { name: "Invalid details", archived: true, version: reason.version })
  lead = await staff.updateEnquiry(lead.id, update({ lostReasonId: reason.id, outcome: lead.outcome, title: "Updated closed enquiry" }))
  assert.equal(lead.lostReasonName, "Invalid contact details")
  assert.equal(lead.outcome, "Phone is disconnected")
  await assert.rejects(staff.updateEnquiry(lead.id, update({ lostReasonId: "" })), expectStatus(400))
  lead = await staff.updateEnquiry(lead.id, update({ status: "QUALIFIED", outcome: lead.outcome }))
  assert.equal(lead.lostReasonId, null)
  assert.equal((await staff.listEnquiries({ lostReasonId: reason.id })).total, 0)
  await assert.rejects(staff.updateEnquiry(lead.id, update({ lostReasonId: reason.id })), expectStatus(400))
  await assert.rejects(staff.updateEnquiry(lead.id, update()), expectStatus(400))
  const entries = await root.crmActivity.findMany({ where: { tenantId: a, enquiryId: lead.id } })
  assert.ok(entries.some(e => e.message.includes("Lost reason: Invalid contact details")))
  // Historical closures remain editable without inventing a classification.
  await root.crmEnquiry.update({ where: { id: lead.id }, data: { status: "CLOSED", outcome: "Original legacy note" } })
  lead = await staff.updateEnquiry(lead.id, update({ outcome: "Original legacy note" }))
  assert.equal(lead.lostReasonId, null)
  assert.equal(lead.outcome, "Original legacy note")
})

test("every opportunity closing path validates reasons and preserves archived historical choices", async () => {
  const contact = await manager.createContact({ name: "Reason opportunity buyer" })
  const pipeline = await manager.createPipeline(pipelineInput("Reason pipeline"))
  const reason = await manager.createLostReason({ name: "Budget mismatch" })
  const input = dealInput(pipeline, contact, staffA)
  await assert.rejects(manager.createOpportunity({ ...input, stageId: pipeline.stages[3].id, lossReason: "A note" }), expectStatus(400))
  const directlyLost = await manager.createOpportunity({ ...input, stageId: pipeline.stages[3].id, lostReasonId: reason.id })
  assert.equal(directlyLost.lostReasonName, reason.name)
  let deal = await manager.createOpportunity(input)
  await assert.rejects(staff.updateOpportunity(deal.id, { ...dealUpdate(deal), stageId: pipeline.stages[3].id }), expectStatus(400))
  deal = await staff.updateOpportunity(deal.id, { ...dealUpdate(deal), stageId: pipeline.stages[3].id, lostReasonId: reason.id })
  assert.equal((await staff.listOpportunities({ lostReasonId: reason.id })).total, 2)
  await manager.updateLostReason(reason.id, { name: "Outside budget", archived: true, version: 1 })
  deal = await staff.updateOpportunity(deal.id, { ...dealUpdate(deal), lostReasonId: reason.id })
  assert.equal(deal.lostReasonName, "Budget mismatch")
  const move = stageId => ({ pipelineId: pipeline.id, stageId, version: deal.version })
  deal = await staff.moveOpportunity(deal.id, move(pipeline.stages[0].id))
  assert.equal(deal.lostReasonId, null)
  await assert.rejects(staff.moveOpportunity(deal.id, { ...move(pipeline.stages[3].id), lostReasonId: reason.id }), expectStatus(400))
  deal = await staff.moveOpportunity(deal.id, { ...move(pipeline.stages[3].id), lostReasonId: defaultLostReason.id })
  assert.equal(deal.lostReasonName, "Not proceeding")
  await assert.rejects(staff.moveOpportunity(deal.id, { ...move(pipeline.stages[0].id), version: 1 }), expectStatus(409))
  // Composite FK rejects a cross-business reason even in a direct database write.
  const foreign = await second.createLostReason({ name: "Outside company" })
  await assert.rejects(root.crmOpportunity.update({ where: { id: deal.id }, data: { lostReasonId: foreign.id } }))
})

