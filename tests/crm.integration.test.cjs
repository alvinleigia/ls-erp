test("conversion default persists atomically with permissions, tenant isolation and database constraints", async () => {
  const input = pipelineInput("Conversion configuration")
  input.stages[1].isConversionDefault = true
  let pipeline = await manager.createPipeline(input)
  assert.equal(pipeline.stages.find(s => s.isConversionDefault).name, "Proposal")
  const update = (record, index) => ({ ...pipelineUpdate(record), stages: pipelineUpdate(record).stages.map((s, i) => ({ ...s, isConversionDefault: i === index })) })
  await assert.rejects(staff.updatePipeline(pipeline.id, update(pipeline, 0)), expectStatus(403))
  await assert.rejects(second.getPipeline(pipeline.id), expectStatus(404))
  assert.equal(await dbB.crmStage.count({ where: { pipelineId: pipeline.id } }), 0)
  const stale = update(pipeline, 0)
  // Move the default earlier in the update order; the unique index must not conflict.
  pipeline = await manager.updatePipeline(pipeline.id, stale)
  assert.equal(pipeline.stages.find(s => s.isConversionDefault).name, "Discovery")
  await assert.rejects(manager.updatePipeline(pipeline.id, stale), expectStatus(409))
  assert.equal((await manager.getPipeline(pipeline.id)).stages.find(s => s.isConversionDefault).name, "Discovery")
  const invalid = update(pipeline, 0); invalid.stages[0].archived = true
  assert.throws(() => manager.updatePipeline(pipeline.id, invalid), /active open stage/)
  await assert.rejects(root.crmStage.update({ where: { id: pipeline.stages[1].id }, data: { isConversionDefault: true } }))
  await assert.rejects(root.crmStage.update({ where: { id: pipeline.stages[0].id }, data: { archived: true } }))
  await assert.rejects(root.crmStage.update({ where: { id: pipeline.stages[2].id }, data: { isConversionDefault: true } }))
  const contact = await manager.createContact({ name: "Conversion configuration buyer" })
  const deal = await manager.createOpportunity(dealInput(pipeline, contact, adminA))
  pipeline = await manager.updatePipeline(pipeline.id, update(pipeline, 1))
  assert.equal((await manager.getOpportunity(deal.id)).stageId, deal.stageId)
  pipeline = await manager.updatePipeline(pipeline.id, update(pipeline, -1))
  assert.equal(pipeline.stages.some(s => s.isConversionDefault), false)
  const foreign = await second.createPipeline(input)
  const cross = update(pipeline, 0); cross.stages.push({ ...pipelineUpdate(foreign).stages[0], name: "Foreign" })
  await assert.rejects(manager.updatePipeline(pipeline.id, cross), /another pipeline/)
  const audit = await root.auditLog.findFirst({ where: { tenantId: a, entityId: pipeline.id, event: "crm.pipeline.updated" }, orderBy: { createdAt: "desc" } })
  assert.ok(audit)
})
