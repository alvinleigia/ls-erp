/* eslint-disable @typescript-eslint/no-require-imports */
const {test}=require('node:test'),assert=require('node:assert/strict')
const {businessNavigation}=require('../application/navigation.ts')
const {permits}=require('../platform/access/policy.ts')
const {moduleKeys}=require('../platform/modules.ts')
const flags=moduleKeys.map(key=>({key,enabled:true,allowed:true}))

test('shared teams have core routes, explicit resource policies and protected security history',()=>{
 const {applicationRouteAccess: access}=require('../application/access-routes.ts')
 const {resourceKeys,accessResources}=require('../platform/access/catalog.ts')
 const {resourceRecordPolicies}=require('../platform/access/resource-policy.ts')
 const {securityEvents}=require('../platform/audit/policy.ts')
 assert.equal(access.routeRequirement('/users/teams/new'),'teams.create')
 assert.equal(accessResources.teams.module,'core')
 assert.deepEqual(Object.keys(resourceRecordPolicies).sort(),[...resourceKeys].sort())
 for(const prefix of ['crm.team.','team.'])assert.ok(securityEvents.OR.some(item=>item.event.startsWith===prefix))
})

test('application route metadata preserves special requirements and prefix boundaries',()=>{
 const {applicationRouteAccess: access}=require('../application/access-routes.ts')
 assert.equal(access.routeResource('/inventory/categories/new'),'inventoryCategories')
 assert.equal(access.routeRequirement('/inventory/categories/new'),'inventoryCategories.create')
 assert.equal(access.routeResource('/inventory-other'),undefined)
 assert.equal(access.routeRequirement('/unknown'),undefined)
 assert.deepEqual(access.routeRequirement('/crm/enquiries/import'),['enquiries.create','contacts.create'])
 assert.deepEqual(access.routeRequirement('/crm/sales/records'),['reports.read','enquiries.read','opportunities.read','activities.read'])
 assert.equal(access.routeRequirement('/settings'),'businessSettings.read')
 assert.equal(access.routeRequirement('/settings/unknown'),undefined)
 assert.equal(access.linkRequirement('/crm/enquiries/new'),'enquiries.create')
 assert.equal(access.linkRequirement('/appointments/new'),undefined)
 assert.ok(access.routeRequirement('/crm/configuration').any.includes('pipelines.read'))
 assert.deepEqual(access.routeRequirement('/crm/activity-configuration'),{any:['activityTypes.read','activityPlans.read','followUpRules.read']})
})

test('platform route resolver accepts application metadata without a CRM registry',()=>{
 const {createRouteAccess}=require('../platform/access/routes.ts')
 const access=createRouteAccess({resources:[['/catalog','services']],protectedLinkPrefixes:['/catalog']})
 assert.equal(access.routeRequirement('/catalog/new'),'services.create')
 assert.equal(access.linkRequirement('/catalog/item'),'services.read')
 assert.equal(access.routeRequirement('/crm/enquiries'),undefined)
 assert.equal(access.linkRequirement('/catalogue'),undefined)
})
test('roles hide denied navigation, reports require source reads, legacy access remains',()=>{
 const limited=businessNavigation(flags,['enquiries.read'])
 assert.deepEqual(limited.flatMap(g=>g.items.map(i=>i.href)),['/crm/enquiries'])
 assert.ok(businessNavigation(flags).length>4)
 assert.equal(businessNavigation(flags,[]).length,0)
 assert.equal(permits({permissions:['contacts.edit']},'contacts.edit'),false)
 assert.equal(permits({},'contacts.edit'),true)
 assert.equal(businessNavigation(flags,['reports.read']).length,0)
})
