test("roster override actions stay visible on mobile and save the selected unavailability", async ({ page }) => {
  const { writes } = await fixture(page)
  await page.route("**/api/shifts/overrides", async route => {
    if (route.request().method() === "GET") return route.fallback()
    writes.push({ path: "/api/shifts/overrides", method: "POST", body: route.request().postDataJSON() })
    return route.fulfill({ json: { createdCount: 1 } })
  })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/shifts/roster")
  await page.getByRole("button", { name: "Next week" }).click()
  await page.getByRole("row").filter({ has: page.getByText("Sam", { exact: true }) }).getByRole("cell", { name: "Off", exact: true }).first().click()
  await expect(page.getByRole("heading", { name: "Change shift", exact: true })).toBeVisible()
  await page.getByLabel("Mark as unavailable", { exact: true }).check()
  const save = page.getByRole("button", { name: "Save override", exact: true })
  const bounds = await save.boundingBox(); expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844)
  await page.screenshot({ path: test.info().outputPath("roster-override-mobile.png"), animations: "disabled" })
  await save.click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  expect(writes[0].body).toMatchObject({ staffId: "staff", isUnavailable: true, templateId: "", skipWeekOff: false, skipHolidays: false })
})

