import { test, expect, type Page } from "@playwright/test"
import { fixture, pattern } from "./workforce-fixtures"
async function choose(page: Page, name: string, value: string) {
  await page.getByRole("button", { name, exact: true }).click()
  await page.getByRole("menuitemradio", { name: value, exact: true }).click()
}

test("leave definitions open read-only; drafts preserve rules through discard and failed saves", async ({ page }) => {
  const { writes, state } = await fixture(page)
  await page.goto("/leaves/leave")
  await expect(page.getByRole("heading", { name: "Request rules" })).toBeVisible()
  await expect(page.getByRole("textbox")).toHaveCount(0)
  await page.getByRole("button", { name: "Edit details" }).click()
  await page.getByLabel("Leave name", { exact: true }).fill("Changed")
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
  await page.getByRole("button", { name: "Discard changes" }).click()
  expect(writes).toHaveLength(0)
  await page.getByRole("button", { name: "Edit details" }).click()
  await expect(page.getByLabel("Leave name", { exact: true })).toHaveValue("Annual leave")
  state.fail = true
  await page.getByRole("button", { name: "Save changes", exact: true }).click()
  await expect(page.getByRole("dialog").getByRole("alert")).toHaveText("This configuration is in use.")
  state.fail = false
  await page.getByRole("button", { name: "Save changes", exact: true }).click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  expect(writes[1].body).toMatchObject({ code: "AL", maxDaysPerRequest: 10, allowCarryForward: true, holidayBothSideAllowed: true, nonClubbableWithIds: [] })
})

