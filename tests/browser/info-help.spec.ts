test("keyboard opening, scrolling, guide links and Escape preserve focus without submitting", async ({ page }) => {
  const trigger = page.getByRole("button", { name: "About Report overview", exact: true })
  await trigger.focus(); await page.keyboard.press("Enter")
  const dialog = page.getByRole("dialog", { name: "Report overview", exact: true })
  await expect(dialog).toBeVisible()
  const region = dialog.getByRole("region", { name: "Report overview details" })
  await region.focus(); await page.keyboard.press("PageDown")
  await expect.poll(() => region.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  await dialog.getByRole("link", { name: "Read the guide" }).click()
  await expect(page.getByText("Guide opened", { exact: true })).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(trigger).toBeFocused()
  await page.keyboard.press("Space")
  await expect(dialog).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(page.getByText("Submissions: 0", { exact: true })).toBeVisible()
  expect(new URL(page.url()).hash).toBe("")
})

