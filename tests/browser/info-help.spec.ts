test("collapsed editor help does not expand its summary or discard edits", async ({ page }) => {
  const details = page.locator("details").filter({ has: page.locator("summary", { hasText: "Collapsed section" }) })
  await page.getByRole("button", { name: "About Collapsed section", exact: true }).click()
  await expect(details).not.toHaveAttribute("open")
  await page.keyboard.press("Escape")
  await details.locator("summary").click()
  await page.getByLabel("Draft field", { exact: true }).fill("Keep this draft")
  await page.getByRole("button", { name: "About Collapsed section", exact: true }).click()
  await page.keyboard.press("Escape")
  await expect(details).toHaveAttribute("open")
  await expect(page.getByLabel("Draft field", { exact: true })).toHaveValue("Keep this draft")
})

