import { test, expect } from "@playwright/test"
import { enumLabel } from "../../lib/enum-label"
import { enquiryStatusLabel } from "../../modules/crm/display-labels"
import { inventoryUnitLabels, INVENTORY_UNIT_OPTIONS } from "../../lib/constants/inventory"

test.beforeEach(({ baseURL }) => test.skip(baseURL !== "http://127.0.0.1:3012", "Synthetic component host only."))
test("built-in labels use sentence case and preserve acronyms and unit symbols", () => {
  for (const [value, label] of Object.entries({ NEW: "New", CONTACTED: "Contacted", IN_PROGRESS: "In progress", NO_ANSWER: "No answer", SELECTED_STAFF: "Selected staff", PREFER_NOT_TO_SAY: "Prefer not to say", NON_GST: "Non-GST", ZERO_RATED: "Zero rated", SEZ_WITH_PAYMENT: "SEZ with payment", SMS: "SMS", GSTIN: "GSTIN", INR: "INR", HSN: "HSN", SAC: "SAC", ID: "ID" })) expect(enumLabel(value)).toBe(label)
  expect(enquiryStatusLabel("CLOSED")).toBe("Lost")
  expect(enumLabel("iPhone Services")).toBe("iPhone Services")
  expect(Object.keys(inventoryUnitLabels)).toEqual([...INVENTORY_UNIT_OPTIONS])
  expect(inventoryUnitLabels.kg).toBe("Kilograms (kg)")
})
test("selected and menu labels agree while enum values, custom names and currencies stay intact", async ({ page }) => {
  await page.goto('/dropdown-labels-fixture')
  await expect(page.locator('#status-label-test')).toHaveText('New')
  await page.locator('#status-label-test').click()
  await expect(page.getByRole('menuitemradio')).toHaveText(['New', 'Contacted', 'Qualified', 'Lost'])
  await page.getByRole('menuitemradio', { name: 'Contacted', exact: true }).click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(page.locator('#status-label-test')).toHaveText('Contacted')
  await page.locator('#kind-label-test').click()
  await expect(page.getByRole('menuitemradio')).toHaveText(['Open', 'Won', 'Lost'])
  await page.getByRole('menuitemradio', { name: 'Won', exact: true }).click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(page.locator('#tax-label-test option')).toHaveText(['Non-GST', 'Zero rated', 'SEZ with payment'])
  await page.locator('#tax-label-test').selectOption('SEZ_WITH_PAYMENT')
  await expect(page.locator('#record-label-test')).toHaveText('ACME COMPANY LTD')
  await page.locator('#record-label-test').click()
  const choices = page.getByRole('listbox', { name: 'Suggestions', exact: true })
  await expect(choices.getByRole('option')).toHaveText(['ACME COMPANY LTD', 'iPhone SERVICES', 'CONTACTED'])
  await choices.getByRole('option', { name: 'iPhone SERVICES', exact: true }).click()
  await expect(choices).toHaveCount(0)
  await expect(page.locator('#record-label-test')).toHaveText('iPhone SERVICES')
  await page.getByRole('button', { name: 'Currency', exact: true }).click()
  await expect(page.getByRole('menuitemradio')).toHaveText(['INR', 'USD'])
  await page.getByRole('menuitemradio', { name: 'USD', exact: true }).click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await page.getByRole('button', { name: 'Save fixture', exact: true }).click()
  await expect(page.getByLabel('submitted values')).toHaveText(JSON.stringify({ status: 'CONTACTED', kind: 'WON', tax: 'SEZ_WITH_PAYMENT' }))
  expect(await page.locator('select[aria-hidden="true"]').first().locator('option').evaluateAll(nodes => nodes.map(n => (n as HTMLOptionElement).value))).toEqual(['NEW', 'CONTACTED', 'QUALIFIED', 'CLOSED'])
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('#status-label-test').click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('dropdown-sentence-case-mobile.png'), fullPage: true, animations: 'disabled' })
})
