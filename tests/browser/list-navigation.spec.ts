test("list codecs reject invalid state and unsafe return addresses", () => {
  const initial = { pageIndex: 0, pageSize: 20 }
  for (const raw of ['null', '{"pageIndex":-1,"pageSize":20}', '{"pageIndex":4,"pageSize":500}', '{"__proto__":{},"pageIndex":4,"pageSize":20}', 'broken']) expect(readListValue(raw, initial, "pagination")).toEqual(initial)
  expect(readListValue('{"pageIndex":4,"pageSize":10}', initial, "pagination")).toEqual({ pageIndex: 4, pageSize: 10 })
  const date = new Date(2026, 9, 5)
  expect(readListValue(listValueText({ from: date }), undefined, "period", { kind: "date-range" })).toEqual({ from: date })
  for (const href of ['//evil.test/list', '/\\evil.test', '/%2f%2fevil.test', '/%252f%252fevil.test', '/auth/signin']) expect(cleanListLocation(href)).toBeNull()
  expect(cleanListLocation('/crm/enquiries?token=secret&l.crm.search=%22alex%22')).toBe('/crm/enquiries?l.crm.search=%22alex%22')
  expect(cleanListLocation('/crm/activities?due=overdue&scope=visible&assignedUserId=user&token=secret')).toBe('/crm/activities?due=overdue&scope=visible&assignedUserId=user')
  expect(rememberedListHref('/crm/enquiries', '/crm/contacts?l.crm.page=4')).toBe('/crm/enquiries')
  expect(rememberedListHref('/crm/sales?view=sales', '/crm/sales?view=team&l.crm.page=4')).toBe('/crm/sales?view=sales')
  const params = new URLSearchParams('l.parent.page=4&l.child.page-stage=6&l.other.page=3')
  resetListPages(params, ['child'], 'l.parent.search')
  expect(params.get('l.child.page-stage')).toBe('1'); expect(params.get('l.other.page')).toBe('3')
})

test("Back, save-return, reload and browser history preserve independent list controls", async ({ page }) => {
  await page.goto('/navigation-fixture')
  await page.getByLabel('Search', { exact: true }).pressSequentially('Pilot enquiry', { delay: 2 })
  await expect(page.getByLabel('Search', { exact: true })).toHaveValue('Pilot enquiry')
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('open')
  await page.getByRole('button', { name: '10 rows', exact: true }).click()
  await page.getByRole('button', { name: 'Page 5', exact: true }).click()
  await page.getByRole('button', { name: 'Related page 3', exact: true }).click()
  await page.getByRole('button', { name: 'History tab', exact: true }).click()
  const list = page.url()
  await page.getByRole('link', { name: 'Open record', exact: true }).click()
  await page.getByLabel('Draft', { exact: true }).fill('Unsaved private text')
  expect(page.url()).not.toContain('private')
  await page.getByRole('link', { name: 'Back to list', exact: true }).click()
  await expect(page.getByLabel('current page')).toHaveText('5')
  await expect(page.getByLabel('page size')).toHaveText('10')
  await expect(page.getByLabel('related page')).toHaveText('3')
  await expect(page.getByLabel('current tab')).toHaveText('history')
  await expect(page.getByLabel('Search', { exact: true })).toHaveValue('Pilot enquiry')
  await page.reload(); await expect(page.getByLabel('current page')).toHaveText('5')
  await page.getByRole('link', { name: 'Open record', exact: true }).click()
  await page.getByRole('button', { name: 'Save and return', exact: true }).click()
  await expect(page.getByLabel('current page')).toHaveText('5')
  await page.goBack(); await expect(page.getByRole('heading', { name: 'Record', exact: true })).toBeVisible()
  await page.goBack(); await expect(page.getByLabel('current page')).toHaveText('5')
  await page.goForward(); await expect(page.getByRole('heading', { name: 'Record', exact: true })).toBeVisible()
  await page.goto(list); await page.getByLabel('Search', { exact: true }).fill('Changed')
  await expect(page.getByLabel('current page')).toHaveText('1')
  await expect(page.getByLabel('related page')).toHaveText('3')
  expect(await page.evaluate(() => JSON.stringify(sessionStorage))).not.toContain('Unsaved private text')
})

