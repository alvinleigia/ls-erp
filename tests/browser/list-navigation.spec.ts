test("the real enquiry list requests a restored page and preserves its filters", async ({ page }) => {
  const requests: URL[] = []
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url()); requests.push(url)
    if (url.pathname === '/api/modules') return route.fulfill({ json: { modules: [{ key: 'crm', allowed: true, enabled: true }], permissions: null } })
    if (url.pathname === '/api/settings/display') return route.fulfill({ json: { settings: { timeZone: 'Asia/Kolkata' } } })
    if (url.pathname === '/api/crm/enquiries/lead-81') return route.fulfill({ json: { id: 'lead-81', title: 'Restored enquiry', status: 'NEW', version: 1, canManage: true, canEdit: true, contactId: 'contact', contact: { id: 'contact', name: 'Pilot contact' }, assignedUserId: 'admin', assignee: { id: 'admin', name: 'Test Admin' }, customFields: [], realEstateEnabled: false } })
    if (url.pathname.includes('custom-fields/form')) return route.fulfill({ json: [] })
    if (url.pathname === '/api/crm/enquiries') return route.fulfill({ json: { items: [{ id: 'lead-81', title: 'Restored enquiry', status: 'NEW', contact: { name: 'Pilot contact' } }], page: Number(url.searchParams.get('page')), pageSize: 20, total: 150, totalPages: 8 } })
    return route.fulfill({ json: { items: [], total: 0, page: 1, pageSize: 20, totalPages: 1 } })
  })
  const params = new URLSearchParams({ 'l.crm-enquiries-all.pagination': JSON.stringify({ pageIndex: 4, pageSize: 20 }), 'l.crm-enquiries-all.search': JSON.stringify('pilot'), 'l.crm-enquiries-all.filter': JSON.stringify('NEW') })
  await page.goto('/crm/enquiries?' + params)
  await expect(page.getByRole('link', { name: 'Restored enquiry', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Pagination', exact: true })).toContainText('Page 5 of 8')
  expect(requests.some(url => url.pathname === '/api/crm/enquiries' && url.searchParams.get('page') === '5' && url.searchParams.get('q') === 'pilot' && url.searchParams.get('status') === 'NEW')).toBe(true)
  await page.reload()
  await expect(page.getByRole('navigation', { name: 'Pagination', exact: true })).toContainText('Page 5 of 8')
  await page.getByRole('link', { name: 'Restored enquiry', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Restored enquiry', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Back to enquiries', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Pagination', exact: true })).toContainText('Page 5 of 8')
  expect(requests.filter(url => url.pathname === '/api/crm/enquiries').every(url => url.searchParams.get('page') === '5')).toBe(true)
})

test("service, inventory, leave and shift lists keep restored pagination on mount", async ({ page }) => {
  const reads: URL[] = []
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url()); reads.push(url)
    if (url.pathname === '/api/modules') return route.fulfill({ json: { modules: ['services', 'inventory', 'leaves', 'shifts'].map(key => ({ key, allowed: true, enabled: true })), permissions: null } })
    if (url.pathname.startsWith('/api/settings')) return route.fulfill({ json: { settings: { timeZone: 'Asia/Kolkata', currency: 'INR', locale: 'en-IN', dateFormat: 'dd/MM/yyyy', firstDayOfWeek: 'MONDAY', workingHours: [] } } })
    return route.fulfill({ json: { items: [], total: 150, totalPages: 15, page: Number(url.searchParams.get('page') || '1'), pageSize: 10 } })
  })
  for (const [path, scope, endpoint] of [['/services/categories', 'service-categories', '/api/service-categories'], ['/inventory/categories', 'inventory-categories', '/api/inventory/categories'], ['/leaves', 'leaves', '/api/leaves/definitions'], ['/shifts', 'shifts', '/api/shifts/templates']]) {
    reads.length = 0
    const params = new URLSearchParams({ [`l.${scope}.pagination`]: JSON.stringify({ pageIndex: 4, pageSize: 10 }) })
    await page.goto(path + '?' + params)
    await expect(page.getByRole('navigation', { name: 'Pagination', exact: true })).toContainText('Page 5 of 15')
    expect(reads.filter(url => url.pathname === endpoint).some(url => url.searchParams.get('page') === '5')).toBe(true)
    expect(reads.filter(url => url.pathname === endpoint).every(url => url.searchParams.get('page') === '5')).toBe(true)
  }
  await page.screenshot({ path: test.info().outputPath('restored-shift-list.png'), fullPage: true, animations: 'disabled' })
})
