import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"

test("team intake supports both entry paths and preserves explicit restrictions", async ({ browser }, info) => {
  test.setTimeout(120_000)
  const fixture = await seed(), admin = await login(browser, fixture.origin, fixture.users.admin.email)
  try {
    await admin.page.goto("/crm/configuration/sales-teams/new")
    await admin.page.getByLabel("Team name", { exact: true }).fill("Flexible sales team")
    await expect(admin.page.getByLabel("Sales workflow", { exact: true })).toHaveText("Enquiries and direct opportunities")
    await admin.page.getByRole("button", { name: "Save sales team", exact: true }).click()
    await expect(admin.page).toHaveURL(/\/sales-teams\/(?!new)[^/]+$/)
    const teamId = admin.page.url().split("/").at(-1)!
    let team = await json(admin.context, `/api/crm/sales-teams/${teamId}`)
    expect(team.workflow).toBe("BOTH")
    team = await json(admin.context, `/api/crm/sales-teams/${teamId}/members`, 200, "POST", { version: team.version, userId: fixture.users.admin.id })
    const contact = await json(admin.context, "/api/crm/contacts", 201, "POST", { name: "Intake buyer" })
    const pipeline = await json(admin.context, "/api/crm/pipelines", 201, "POST", { name: "Intake sales", stages: [{ name: "Open", kind: "OPEN", probability: 10, color: "#2563eb" }, { name: "Won", kind: "WON", probability: 100, color: "#00aa00" }, { name: "Lost", kind: "LOST", probability: 0, color: "#aa0000" }] })
    const leadInput = { title: "Flexible new enquiry", salesTeamId: teamId, contactId: contact.id, assignedUserId: fixture.users.admin.id }
    const dealInput = { ...leadInput, title: "Flexible direct deal", pipelineId: pipeline.id, stageId: pipeline.stages.find((s: { kind: string }) => s.kind === "OPEN").id, amount: "100", currency: "INR", expectedCloseOn: "2026-12-31" }
    const direct = await json(admin.context, "/api/crm/opportunities", 201, "POST", dealInput)
    expect(direct.enquiryId).toBeNull()
    const lead = await json(admin.context, "/api/crm/enquiries", 201, "POST", leadInput)
    expect(lead.status).toBe("NEW")
    const converted = await json(admin.context, "/api/crm/opportunities", 201, "POST", { ...dealInput, enquiryId: lead.id, enquiryVersion: lead.version })
    expect(converted.enquiryId).toBe(lead.id)
    await admin.page.goto(`/crm/configuration/sales-teams/${teamId}`)
    await admin.page.getByRole("button", { name: "Edit team details", exact: true }).click()
    const dialog = admin.page.getByRole("dialog")
    await dialog.getByLabel("Sales workflow", { exact: true }).click()
    await admin.page.screenshot({ path: info.outputPath("workflow-desktop.png"), fullPage: true, animations: "disabled" })
    await admin.page.getByRole("menuitemradio", { name: "Qualify enquiries first", exact: true }).click()
    await dialog.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await json(admin.context, "/api/crm/opportunities", 400, "POST", dealInput)
    expect((await json(admin.context, `/api/crm/opportunities/${direct.id}`)).salesTeamId).toBe(teamId)
    await admin.page.getByRole("button", { name: "Edit team details", exact: true }).click()
    await dialog.getByLabel("Sales workflow", { exact: true }).click()
    await admin.page.getByRole("menuitemradio", { name: "Direct opportunities only", exact: true }).click()
    await dialog.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await json(admin.context, "/api/crm/enquiries", 400, "POST", leadInput)
    await json(admin.context, "/api/crm/opportunities", 201, "POST", dealInput)
    await admin.page.setViewportSize({ width: 390, height: 844 })
    await admin.page.getByRole("button", { name: "Edit team details", exact: true }).click()
    await dialog.getByLabel("Sales workflow", { exact: true }).click()
    await admin.page.screenshot({ path: info.outputPath("workflow-mobile.png"), fullPage: true, animations: "disabled" })
    await admin.page.getByRole("menuitemradio", { name: "Enquiries and direct opportunities", exact: true }).click()
    await dialog.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(dialog).toHaveCount(0)
    expect((await json(admin.context, `/api/crm/sales-teams/${teamId}`)).workflow).toBe("BOTH")
    expect(await admin.page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  } finally { await admin.context.close(); await fixture.db.end() }
})
