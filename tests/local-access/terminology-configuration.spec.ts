  expect(response.request().postDataJSON()).toMatchObject({ scope: "ENQUIRY", code: "original_field", name: "Original field name", type: "TEXT" })
  await expect(admin.page.getByRole("cell", { name: "Leads", exact: true })).toBeVisible()
  await admin.page.getByRole("link", { name: "Original field name", exact: true }).click()
  await expect(admin.page.locator("dd").filter({ hasText: /^Leads$/ })).toBeVisible()
