import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"

test.describe.configure({ mode: "serial" })
let fixture: Awaited<ReturnType<typeof seed>>, admin: Awaited<ReturnType<typeof login>>
let contact: { id: string }, account: { id: string }, rule: { id: string }, plan: { id: string }
async function rename(labels: Record<string, string | null>) {
  const current = await json(admin.context, "/api/settings/terminology")
  await json(admin.context, "/api/settings/terminology", 200, "PATCH", { version: current.version, changes: Object.entries(labels).map(([key, label]) => ({ key, label })) })
  await admin.page.evaluate(() => window.dispatchEvent(new Event("terminology-changed")))
}
test.beforeAll(async ({ browser }) => {
  fixture = await seed(); admin = await login(browser, fixture.origin, fixture.users.admin.email)
  contact = await json(admin.context, "/api/crm/contacts", 201, "POST", { name: "Original contact", email: "config@example.test" })
  account = await json(admin.context, "/api/crm/accounts", 201, "POST", { name: "Original account" })
  await json(admin.context, `/api/crm/contacts/${contact.id}/accounts`, 200, "POST", { accountId: account.id })
  const step = { title: "Original step", type: "CALL", callDirection: "OUTBOUND", dayOffset: 1, priority: 2, description: "Original instructions", reminderTime: null }
  rule = await json(admin.context, "/api/crm/follow-up-rules", 201, "POST", { name: "Original rule", sourceType: "CALL", outcome: "NO_ANSWER", maxDepth: 3, nextStep: step })
  plan = await json(admin.context, "/api/crm/activity-plans", 201, "POST", { name: "Original plan", description: "Original purpose", steps: [step] })
  await rename({ "crm.activity.singular": "Touchpoint", "crm.activity.plural": "Touchpoints", "crm.enquiry.singular": "Prospect", "crm.enquiry.plural": "Prospects", "crm.opportunity.singular": "Deal", "crm.opportunity.plural": "Deals", "crm.contact.singular": "Person", "crm.account.singular": "Company", "crm.account.plural": "Companies", "realEstate.project.plural": "Developments" })
})
test.afterAll(async () => { await admin?.context.close(); await fixture?.db.end() })

test("configuration links and activity type drafts resolve labels with stable save values", async ({}, testInfo) => {
  await admin.page.goto("/crm/activity-configuration")
  await expect(admin.page.getByRole("heading", { name: "Touchpoint configuration", exact: true })).toBeVisible()
  await admin.page.screenshot({ path: testInfo.outputPath("configuration-desktop.png"), animations: "disabled", fullPage: true })
  await admin.page.getByRole("link", { name: /Touchpoint types/ }).click()
  await expect(admin.page).toHaveURL(/\/crm\/activity-types$/)
  await admin.page.getByRole("button", { name: "New Touchpoint type", exact: true }).click()
  const drawer = admin.page.getByRole("dialog")
  await drawer.getByLabel("Touchpoint type name", { exact: true }).fill("Original type name")
  await drawer.getByLabel("Default instructions", { exact: true }).fill("Keep instructions")
  await rename({ "crm.activity.singular": "Action" })
  await expect(drawer.getByLabel("Action type name", { exact: true })).toHaveValue("Original type name")
  await expect(drawer.getByLabel("Default instructions", { exact: true })).toHaveValue("Keep instructions")
  await admin.page.setViewportSize({ width: 390, height: 844 })
  expect(await admin.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await admin.page.screenshot({ path: testInfo.outputPath("configuration-draft-mobile.png"), animations: "disabled", fullPage: true })
  const saved = admin.page.waitForResponse(r => r.url().endsWith("/api/crm/activity-types") && r.request().method() === "POST")
  await drawer.getByRole("button", { name: "Save Action type", exact: true }).click()
  const response = await saved; expect(response.status()).toBe(201)
  expect(response.request().postDataJSON()).toMatchObject({ name: "Original type name", baseType: "MEETING", defaultInstructions: "Keep instructions" })
  await expect(admin.page.getByRole("cell", { name: "Original type name", exact: true })).toBeVisible()
  await admin.page.setViewportSize({ width: 1280, height: 900 })
  await rename({ "crm.activity.singular": "Touchpoint" })
})

