import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"

test("project activity composition preserves parent/child scope and ordinary CRM actions", async ({ browser }, testInfo) => {
  const fixture = await seed(), { context, page } = await login(browser, fixture.origin, fixture.users.admin.email)
  try {
    const project = await json(context, "/api/real-estate/projects", 201, "POST", { name: "Shared development", code: "VIEW-P", location: "Pune" })
    const child = await json(context, "/api/real-estate/projects", 201, "POST", { name: "Phase One", code: "VIEW-C", parentId: project.id })
    const contact = await json(context, "/api/crm/contacts", 201, "POST", { name: "View customer", email: "views@example.test" })
    for (const [title, subprojectId] of [["Parent follow-up", undefined], ["Phase follow-up", child.id]] as const) {
      const lead = await json(context, "/api/crm/enquiries", 201, "POST", { title, contactId: contact.id, assignedUserId: fixture.users.admin.id, propertyContext: { projectId: project.id, subprojectId } })
      await json(context, "/api/crm/work", 201, "POST", { title, contactId: contact.id, enquiryId: lead.id, assignedUserId: fixture.users.admin.id, type: "TASK", dueOn: "2030-01-01" })
    }
    const requests: URL[] = []
    page.on("request", request => { const url = new URL(request.url()); if (url.pathname === "/api/crm/work" && request.method() === "GET") requests.push(url) })
    await page.goto(`/crm/projects/${project.id}`)
    await page.getByRole("tab", { name: "Activities", exact: true }).click()
    await expect(page.getByRole("link", { name: "Parent follow-up", exact: true }).filter({ visible: true })).toBeVisible()
    await expect(page.getByRole("link", { name: "Phase follow-up", exact: true }).filter({ visible: true })).toBeVisible()
    expect(requests.at(-1)?.searchParams.get("projectId")).toBe(project.id)
    expect(requests.at(-1)?.searchParams.has("subprojectId")).toBe(false)
    await expect(page.getByRole("link", { name: "Schedule activity", exact: true })).toHaveCount(0)
    await expect(page.getByText(/Schedule site visits as meetings/)).toBeVisible()
    await page.goto(`/crm/projects/${child.id}`)
    await page.getByRole("tab", { name: "Activities", exact: true }).click()
    await expect(page.getByRole("link", { name: "Phase follow-up", exact: true }).filter({ visible: true })).toBeVisible()
    await expect(page.getByRole("link", { name: "Parent follow-up", exact: true })).toHaveCount(0)
    expect(requests.at(-1)?.searchParams.get("subprojectId")).toBe(child.id)
    const count = requests.length
    const terminology = await json(context, "/api/settings/terminology")
    await json(context, "/api/settings/terminology", 200, "PATCH", { version: terminology.version, changes: [{ key: "crm.enquiry.singular", label: "Prospect" }] })
    await page.evaluate(() => window.dispatchEvent(new Event("terminology-changed")))
    await expect(page.getByText("Schedule site visits as meetings and follow-ups as calls from a linked Prospect or opportunity.", { exact: true })).toBeVisible()
    expect(requests.length).toBe(count)
    await page.setViewportSize({ width: 390, height: 844 })
    await expect(page.getByRole("textbox", { name: "Search activity titles", exact: true })).toHaveAttribute("placeholder", "Search activities…")
    await expect(page.getByText("01/01/2030 · All day", { exact: true }).filter({ visible: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath("project-activities-mobile.png"), fullPage: true, animations: "disabled" })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await json(context, "/api/modules", 200, "PATCH", { key: "realEstate", enabled: false })
    await page.evaluate(() => window.dispatchEvent(new Event("business-modules-changed")))
    await expect(page.getByText(/Schedule site visits as meetings/)).toHaveCount(0)
    expect(requests.length).toBe(count)
    await json(context, `/api/crm/work?projectId=${project.id}`, 403)
    await page.goto(`/crm/contacts/${contact.id}`)
    await page.getByRole("tab", { name: "Activities", exact: true }).click()
    await expect(page.getByRole("link", { name: "Schedule activity", exact: true })).toBeVisible()
    await expect(page.getByRole("button", { name: "More actions", exact: true })).toBeVisible()
    await expect(page.getByText(/Schedule site visits as meetings/)).toHaveCount(0)
    await expect(page.getByRole("link", { name: "Phase follow-up", exact: true }).filter({ visible: true })).toBeVisible()
    expect(requests.at(-1)?.searchParams.get("contactId")).toBe(contact.id)
    expect(requests.at(-1)?.searchParams.has("projectId")).toBe(false)
  } finally { await context.close(); await fixture.db.end() }
})

test("neutral quotation editor retains industry context and saved revisions when the addon is disabled", async ({ browser }, testInfo) => {
  const fixture = await seed(), { context, page } = await login(browser, fixture.origin, fixture.users.admin.email)
  try {
    const contact = await json(context, "/api/crm/contacts", 201, "POST", { name: "Document customer", email: "document-view@example.test" })
    const project = await json(context, "/api/real-estate/projects", 201, "POST", { name: "Retained development", code: "DOC-VIEW" })
    const pipeline = await json(context, "/api/crm/pipelines", 201, "POST", { name: "General sales", stages: [{ name: "Qualified", kind: "OPEN", probability: 20, color: "#123456" }, { name: "Won", kind: "WON", probability: 100, color: "#16a34a" }, { name: "Lost", kind: "LOST", probability: 0, color: "#dc2626" }] })
    const deal = await json(context, "/api/crm/opportunities", 201, "POST", { title: "Document deal", contactId: contact.id, assignedUserId: fixture.users.admin.id, pipelineId: pipeline.id, stageId: pipeline.stages[0].id, amount: "1000", currency: "INR", expectedCloseOn: "2030-11-06", propertyContext: { projectId: project.id } })
    await page.goto(`/crm/quotations/new?opportunityId=${deal.id}`)
    await expect(page.getByLabel("Business name", { exact: true })).toBeVisible()
    await expect(page.getByLabel("Registration reference (optional)", { exact: true })).toBeVisible()
    await page.getByText("Linked records", { exact: true }).click()
    await expect(page.getByText("Retained development", { exact: true })).toBeVisible()
    await page.getByText("Price and discount", { exact: true }).click()
    await expect(page.getByText("Quantity × rate. Enter the quantity and unit used for pricing.", { exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath("quotation-neutral-desktop.png"), fullPage: true, animations: "disabled" })
    const defaults = await json(context, `/api/crm/opportunities/${deal.id}/quotations/defaults`)
    const saved = await json(context, `/api/crm/opportunities/${deal.id}/quotations`, 201, "POST", { content: { ...defaults.content, registration: "RERA-original", details: [{ label: "Plot number", value: "A-101" }] } })
    const before = await json(context, `/api/crm/quotations/${saved.id}`)
    await json(context, "/api/modules", 200, "PATCH", { key: "realEstate", enabled: false })
    await page.goto(`/crm/quotations/new?opportunityId=${deal.id}`)
    await expect(page.getByLabel("Business name", { exact: true })).toBeVisible()
    await expect(page.getByText("Linked records", { exact: true })).toHaveCount(0)
    expect((await json(context, `/api/crm/opportunities/${deal.id}/quotations/defaults`)).context).toEqual([])
    await page.goto(`/crm/quotations/${saved.id}`)
    await expect(page.getByText("Retained development", { exact: true })).toBeVisible()
    await expect(page.getByText("RERA-original", { exact: true })).toBeVisible()
    await expect(page.getByText("A-101", { exact: true })).toBeVisible()
    expect((await json(context, `/api/crm/quotations/${saved.id}`)).snapshot).toEqual(before.snapshot)
  } finally { await context.close(); await fixture.db.end() }
})
