import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"
import { emptyQuotationContent } from "../../modules/sales-documents/quotation-validation"

test("shared booking review, saved date/reference, multiple units and independent agreement status", async ({ browser }) => {
  test.setTimeout(180_000)
  const f=await seed(),admin=await login(browser,f.origin,f.users.admin.email),{page,context}=admin
  try{
    await f.db.query('UPDATE "TenantModule" SET enabled=false WHERE "tenantId"=$1 AND key=\'realEstate\'',[f.slug])
    for(const key of ['salesOrders','catalog'])await f.db.query('INSERT INTO "TenantModule" ("tenantId",key,allowed,enabled,"updatedAt") VALUES ($1,$2,true,true,now())',[f.slug,key])
    const terminology=await json(context,'/api/settings/terminology')
    await json(context,'/api/settings/terminology',200,'PATCH',{version:terminology.version,changes:[{key:'salesOrders.order.singular',label:'Booking'},{key:'salesOrders.order.plural',label:'Bookings'}]})
    const person=await json(context,'/api/crm/contacts',201,'POST',{name:'QA Booking buyer'})
    const pipeline=await json(context,'/api/crm/pipelines',201,'POST',{name:'Booking checks',stages:[{name:'Open',kind:'OPEN',probability:10,color:'#123456'},{name:'Won',kind:'WON',probability:100,color:'#00aa00'},{name:'Lost',kind:'LOST',probability:0,color:'#aa0000'}]})
    const deal=await json(context,'/api/crm/opportunities',201,'POST',{title:'Shared equipment booking',contactId:person.id,assignedUserId:f.users.admin.id,pipelineId:pipeline.id,stageId:pipeline.stages[0].id,amount:'300',currency:'INR',expectedCloseOn:'2027-01-01'})
    const items=[]
    for(const [code,price] of [['QA-A','100'],['QA-B','200']])items.push(await json(context,'/api/catalog/items',201,'POST',{code,name:`Equipment ${code}`,kind:'UNIT',price,currency:'INR',unit:'each'}))
    const quote=await json(context,`/api/crm/opportunities/${deal.id}/quotations`,201,'POST',{content:{...structuredClone(emptyQuotationContent),title:'Equipment booking',supplierName:'QA Industries',currency:'INR',lines:items.map(item=>({description:item.name,quantity:'1',unit:'each',rate:String(item.price),catalogItemId:item.id,catalogItemVersion:item.version}))}})
    const prepared=await json(context,`/api/sales-orders/context?quotationId=${quote.id}&revision=1`)
    expect(prepared.existing).toBeNull()
    await page.goto(`/crm/quotations/${quote.id}`)
    await page.getByRole('button',{name:'Create Booking',exact:true}).click()
    const dialog=page.getByRole('dialog',{name:'Review Booking',exact:true})
    await expect(dialog.getByLabel('Booking date',{exact:true})).toHaveValue(prepared.orderedOn)
    await dialog.getByLabel('Booking date',{exact:true}).fill('2026-01-01')
    await page.setViewportSize({width:390,height:844})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await expect(dialog.getByRole('button',{name:'Create draft',exact:true})).toBeInViewport()
    await page.screenshot({path:test.info().outputPath('booking-review-mobile.png'),fullPage:true,animations:'disabled'})
    await dialog.getByRole('button',{name:'Create draft',exact:true}).click()
    await expect(page).toHaveURL(/\/sales-orders\/[^/]+$/)
    const id=page.url().split('/').pop()!,order=await json(context,`/api/sales-orders/${id}`)
    expect(order.reference).toBe('SO-000001');expect(order.orderedOn.slice(0,10)).toBe('2026-01-01')
    await expect(page.getByText(order.reference,{exact:true})).toBeVisible()
    await expect(page.getByText('Booking date',{exact:true})).toHaveCount(1)
    await expect(page.getByText('Booking date on quotation',{exact:true})).toBeVisible()
    await expect(page.getByRole('heading',{name:'Confirmation review',exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Reserve unit',exact:true}).first().click()
    await page.getByRole('button',{name:'Save reservation',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByText('Reserved',{exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Confirm Booking',exact:true}).click()
    await page.getByRole('button',{name:'Confirm agreement',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('button',{name:'Allocate unit',exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Allocate unit',exact:true}).click()
    await page.getByRole('button',{name:'Confirm allocation',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByText('Allocated',{exact:true})).toBeVisible()
    expect((await json(context,`/api/sales-orders/${id}`)).status).toBe('CONFIRMED')
    await page.setViewportSize({width:1280,height:900})
    await page.screenshot({path:test.info().outputPath('booking-allocated-desktop.png'),fullPage:true,animations:'disabled'})
    await page.goto(`/crm/quotations/${quote.id}`)
    await page.getByRole('button',{name:'Create Booking',exact:true}).click()
    await expect(page.getByRole('dialog')).toContainText(order.reference)
    await expect(page.getByRole('button',{name:'Create draft',exact:true})).toHaveCount(0)
    await page.getByRole('button',{name:'Open existing order',exact:true}).click()
    await expect(page).toHaveURL(new RegExp(`/sales-orders/${id}$`))
    await page.getByRole('button',{name:'Cancel Booking',exact:true}).click()
    await page.getByLabel('Cancellation reason',{exact:true}).fill('Replace the equipment booking')
    await page.getByRole('button',{name:'Cancel order',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByText('Released',{exact:true})).toBeVisible()
    expect((await json(context,`/api/sales-orders/${id}`)).reference).toBe(order.reference)
    await page.goto('/sales-orders')
    await page.getByRole('textbox',{name:'Search orders',exact:true}).fill(order.reference)
    await expect(page.getByRole('link',{name:'Equipment booking',exact:true})).toBeVisible()
    expect((await json(context,`/api/sales-orders?q=${order.reference}`)).total).toBe(1)
    await page.setViewportSize({width:390,height:844})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.screenshot({path:test.info().outputPath('booking-reference-search-mobile.png'),fullPage:true,animations:'disabled'})
  }finally{await context.close();await f.db.end()}
})
