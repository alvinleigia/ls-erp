test("own-only staff cannot open team reporting and a denied refresh clears previous figures", async ({ browser }) => {
  test.setTimeout(120_000)
  const f = await seed(), admin = await login(browser, f.origin, f.users.admin.email), staff = await login(browser, f.origin, f.users.staff.email), manager = await login(browser, f.origin, f.users.manager.email)
  try {
    await json(staff.context, "/api/crm/reports/sales/team", 403)
    await staff.page.goto("/crm/sales")
    await expect(staff.page.getByRole("tab", { name: "Sales summary" })).toBeVisible()
    await expect(staff.page.getByRole("tab", { name: "Team performance" })).toHaveCount(0)
    await manager.page.goto("/crm/sales")
    await manager.page.getByRole("tab", { name: "Team performance" }).click()
    await expect(manager.page.getByText("No members or records match this selection.", { exact: true })).toBeVisible()
    const current = await json(admin.context, `/api/access/users/${f.users.manager.id}`)
    await json(admin.context, `/api/access/users/${f.users.manager.id}`, 200, "PATCH", { version: current.accessPolicy.version, roleIds: current.accessAssignments.map((r: { roleId: string }) => r.roleId), rules: { ...current.accessPolicy.rules, "reports.read": "NONE" } })
    await manager.page.getByRole("button", { name: "Refresh", exact: true }).click()
    await expect(manager.page.getByRole("alert").filter({ hasText: /access|permission|report/i }).first()).toBeVisible()
    await expect(manager.page.getByText("No members or records match this selection.", { exact: true })).toHaveCount(0)
  } finally { await Promise.all([admin.context.close(), staff.context.close(), manager.context.close()]); await f.db.end() }
})
