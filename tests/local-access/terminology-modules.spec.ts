import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"
import { emptyQuotationContent } from "../../modules/sales-documents/quotation-validation"

test.describe.configure({ mode: "serial" })
let fixture: Awaited<ReturnType<typeof seed>>, admin: Awaited<ReturnType<typeof login>>
let project: { id: string }, child: { id: string }, contact: { id: string }, lead: { id: string }, deal: { id: string }, quote: { id: string }
let original: { snapshot: unknown; version: number }
async function rename(labels: Record<string, string | null>) {
  const current = await json(admin.context, "/api/settings/terminology")
  await json(admin.context, "/api/settings/terminology", 200, "PATCH", { version: current.version, changes: Object.entries(labels).map(([key, label]) => ({ key, label })) })
  await admin.page.evaluate(() => window.dispatchEvent(new Event("terminology-changed")))
}
test.beforeAll(async ({ browser }) => {
  fixture = await seed(); admin = await login(browser, fixture.origin, fixture.users.admin.email)
  project = await json(admin.context, "/api/real-estate/projects", 201, "POST", { name: "Original project name", code: "TERMS-P", location: "Pune", currency: "INR" })
  child = await json(admin.context, "/api/real-estate/projects", 201, "POST", { name: "Original phase name", code: "TERMS-C", parentId: project.id })
  contact = await json(admin.context, "/api/crm/contacts", 201, "POST", { name: "Original customer", email: "modules@example.test" })
  lead = await json(admin.context, "/api/crm/enquiries", 201, "POST", { title: "Original enquiry", contactId: contact.id, assignedUserId: fixture.users.admin.id, propertyContext: { projectId: project.id, subprojectId: child.id } })
  const pipeline = await json(admin.context, "/api/crm/pipelines", 201, "POST", { name: "Local pipeline", stages: [
    { name: "Qualified", kind: "OPEN", probability: 20, color: "#123456" }, { name: "Won", kind: "WON", probability: 100, color: "#008800" }, { name: "Lost", kind: "LOST", probability: 0, color: "#880000" },
  ] })
  deal = await json(admin.context, "/api/crm/opportunities", 201, "POST", { title: "Original opportunity", contactId: contact.id, assignedUserId: fixture.users.admin.id, pipelineId: pipeline.id, stageId: pipeline.stages[0].id, amount: "1000", currency: "INR", expectedCloseOn: "2030-11-06", propertyContext: { projectId: project.id, subprojectId: child.id } })
  quote = await json(admin.context, `/api/crm/opportunities/${deal.id}/quotations`, 201, "POST", { content: { ...structuredClone(emptyQuotationContent), title: "Original quotation title", supplierName: "Local supplier", currency: "INR", bookingDate: "2030-10-07", lines: [{ description: "Original line", quantity: "1", unit: "unit", rate: "1000" }], instalments: [{ label: "Original instalment", percent: "100", days: 0, note: "Original note" }] } })
  original = await json(admin.context, `/api/crm/quotations/${quote.id}`)
  await rename({ "crm.activity.singular": "Touchpoint", "crm.activity.plural": "Touchpoints", "crm.enquiry.singular": "Prospect", "crm.opportunity.singular": "Deal", "realEstate.project.singular": "Development", "realEstate.project.plural": "Developments", "realEstate.subproject.singular": "Phase", "realEstate.subproject.plural": "Phases", "salesDocuments.quotation.singular": "Offer", "salesDocuments.quotation.plural": "Offers", "paymentPlans.paymentPlan.singular": "Payment schedule", "paymentPlans.paymentPlan.plural": "Payment schedules" })
})
test.afterAll(async () => { await admin?.context.close(); await fixture?.db.end() })

test("project details, child creation and property selectors share labels while preserving IDs", async () => {
  await admin.page.goto(`/crm/projects/${project.id}`)
  await expect(admin.page.getByRole("heading", { name: "Original project name", exact: true })).toBeVisible()
  await admin.page.getByRole("button", { name: "Edit Development", exact: true }).click()
  const editor = admin.page.getByRole("dialog")
  await expect(editor.getByLabel("Development name", { exact: true })).toHaveValue("Original project name")
  await editor.getByLabel("Development name", { exact: true }).fill("Unsaved project draft")
  await rename({ "realEstate.project.singular": "Estate" })
  await expect(editor.getByLabel("Estate name", { exact: true })).toHaveValue("Unsaved project draft")
  await expect(editor.getByText("Codes are unique across Developments and Phases in this business.", { exact: true })).toBeVisible()
  await admin.page.goto(`/crm/projects/${project.id}`)
  await admin.page.getByRole("tab", { name: "Team", exact: true }).click()
  await expect(admin.page.getByText("No staff assigned. Only managers can access this Estate.", { exact: true })).toBeVisible()
  await admin.page.getByRole("tab", { name: "Phases", exact: true }).click()
  await admin.page.getByRole("link", { name: "New Phase", exact: true }).click()
  await expect(admin.page).toHaveURL(new RegExp(`parentId=${project.id}`))
  await expect(admin.page.getByLabel("Phase name", { exact: true })).toBeVisible()
  await admin.page.goto(`/crm/projects/${child.id}`)
  await admin.page.getByRole("tab", { name: "Sales", exact: true }).click()
  await admin.page.getByRole("link", { name: "New Prospect", exact: true }).click()
  await expect(admin.page.getByLabel("Estate (optional)", { exact: true })).toContainText("Original project name")
  await expect(admin.page.getByLabel("Phase (optional)", { exact: true })).toContainText("Original phase name")
  expect((await json(admin.context, `/api/real-estate/projects/${project.id}`)).name).toBe("Original project name")
})

test("activity scheduling, list and edit drawer use terminology with stable payloads", async () => {
  await admin.page.goto(`/crm/activities/new?enquiryId=${lead.id}&contactId=${contact.id}`)
  await expect(admin.page.getByRole("heading", { name: "Schedule Touchpoint", exact: true })).toBeVisible()
  await expect(admin.page.getByLabel("Related to", { exact: true })).toContainText("Prospect")
  await admin.page.getByLabel("Touchpoint title", { exact: true }).fill("Original activity title")
  const response = admin.page.waitForResponse(r => r.url().endsWith("/api/crm/work") && r.request().method() === "POST")
  await admin.page.getByRole("button", { name: "Save Touchpoint", exact: true }).click()
  const saved = await response; expect(saved.status()).toBe(201)
  const work = await saved.json()
  expect(work.enquiryId).toBe(lead.id); expect(work.type).toBe("TASK"); expect(work.title).toBe("Original activity title")
  await expect(admin.page).toHaveURL(new RegExp(`/crm/activities/${work.id}$`))
  await admin.page.getByRole("button", { name: "Edit touchpoint details", exact: true }).click()
  const editor = admin.page.getByRole("dialog")
  await editor.getByLabel("Touchpoint title", { exact: true }).fill("Unsaved activity draft")
  await rename({ "crm.activity.singular": "Action" })
  await expect(editor.getByLabel("Action title", { exact: true })).toBeVisible()
  await expect(editor.getByLabel("Action title", { exact: true })).toHaveValue("Unsaved activity draft")
  await admin.page.goto("/crm/activities")
  await expect(admin.page.getByRole("columnheader", { name: "Action", exact: true })).toBeVisible()
  await expect(admin.page.getByRole("link", { name: "Schedule Action", exact: true })).toBeVisible()
  expect((await json(admin.context, `/api/crm/work/${work.id}`)).title).toBe("Original activity title")
})

test("quotation and payment controls refresh without changing saved snapshots or draft schedules", async ({}, testInfo) => {
  await admin.page.goto("/crm/quotations")
  await expect(admin.page.getByRole("heading", { name: "Offers", exact: true })).toBeVisible()
  await admin.page.getByRole("link", { name: "Original quotation title", exact: true }).click()
  await expect(admin.page.getByRole("heading", { name: /Original quotation title.*version 1/ })).toBeVisible()
  await admin.page.getByRole("tab", { name: "Payment schedule", exact: true }).click()
  await expect(admin.page.getByText("Original instalment", { exact: true })).toBeVisible()
  // The saved summary retains the heading captured before the terminology override.
  await expect(admin.page.getByRole("heading", { name: "Instalment schedule", exact: true })).toBeVisible()
  await admin.page.getByRole("button", { name: "Edit instalment schedule", exact: true }).click()
  const editor = admin.page.getByRole("dialog")
  await expect(editor.getByText("Payment schedule", { exact: true })).toBeVisible()
  await editor.locator("#instalment-note-0").fill("Unsaved schedule note")
  await rename({ "paymentPlans.paymentPlan.singular": "Instalment plan" })
  await expect(editor.getByText("Instalment plan", { exact: true })).toBeVisible()
  await expect(editor.locator("#instalment-note-0")).toHaveValue("Unsaved schedule note")
  await admin.page.screenshot({ path: testInfo.outputPath("renamed-payment-drawer.png"), fullPage: true, animations: "disabled" })
  await admin.page.setViewportSize({ width: 390, height: 844 })
  expect(await admin.page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await admin.page.screenshot({ path: testInfo.outputPath("renamed-payment-mobile.png"), fullPage: true, animations: "disabled" })
  const after = await json(admin.context, `/api/crm/quotations/${quote.id}`)
  expect(after.snapshot).toEqual(original.snapshot); expect(after.version).toBe(original.version)
  await json(admin.context, "/api/modules", 200, "PATCH", { key: "paymentPlans", enabled: false })
  await admin.page.reload()
  await expect(admin.page.getByRole("tab", { name: "Payment plan", exact: true })).toBeVisible()
  await expect(admin.page.getByRole("button", { name: "Edit details", exact: true })).toBeDisabled()
  expect((await json(admin.context, `/api/crm/quotations/${quote.id}`)).snapshot).toEqual(original.snapshot)
})
