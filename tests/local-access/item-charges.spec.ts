import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"

test("item defaults are reviewed, overridden and explicitly refreshed in a quotation", async ({ browser }, testInfo) => {
  test.setTimeout(180_000)
  const f = await seed(), { page, context } = await login(browser, f.origin, f.users.admin.email)
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  try {
    await f.db.query('INSERT INTO "TenantModule" ("tenantId",key,allowed,enabled,"updatedAt") VALUES ($1,\'catalog\',true,true,now())', [f.slug])
    await page.goto("/catalog/new")
    await page.getByLabel("Unique code", { exact: true }).fill("CHARGE-01")
    await page.getByLabel("Name", { exact: true }).fill("Charge test product")
    await page.getByLabel("Price", { exact: true }).fill("1000")
    await page.locator("summary").filter({ hasText: "Item charges" }).click()
    await page.getByRole("button", { name: "Add item charge", exact: true }).click()
    await page.getByLabel("Item charge name", { exact: true }).fill("PLC")
    await page.getByLabel("Item charge percentage", { exact: true }).fill("8")
    await page.screenshot({ path: testInfo.outputPath("item-charge-desktop.png"), fullPage: true })
    await page.getByRole("button", { name: "Save item", exact: true }).click()
    await expect(page).toHaveURL(/\/catalog\/(?!new)[^/]+$/)
    const itemId = page.url().split("/").pop()!
    await page.getByRole("tab", { name: "Item charges", exact: true }).click()
    await expect(page.getByText("8% of this item line", { exact: false })).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: testInfo.outputPath("item-charge-mobile.png"), fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.setViewportSize({ width: 1280, height: 900 })
    const contact = await json(context, "/api/crm/contacts", 201, "POST", { name: "Charge test buyer" })
    const pipeline = await json(context, "/api/crm/pipelines", 201, "POST", { name: "Charge test sales", stages: [{ name: "Open", kind: "OPEN", probability: 10, color: "#123456" }, { name: "Won", kind: "WON", probability: 100, color: "#00aa00" }, { name: "Lost", kind: "LOST", probability: 0, color: "#aa0000" }] })
    const deal = await json(context, "/api/crm/opportunities", 201, "POST", { title: "Charge test sale", contactId: contact.id, assignedUserId: f.users.admin.id, pipelineId: pipeline.id, stageId: pipeline.stages[0].id, amount: "1000", currency: "INR", expectedCloseOn: "2027-12-31" })
    await page.goto(`/crm/quotations/new?opportunityId=${deal.id}`)
    await page.locator("summary").filter({ hasText: "Price and discount" }).click()
    await page.getByRole("combobox", { name: "Catalog item (optional)", exact: true }).click()
    await page.getByRole("option", { name: /Charge test product/ }).click()
    await expect(page.getByLabel("Item charge percentage", { exact: true })).toHaveValue("8")
    await page.getByLabel("Item charge percentage", { exact: true }).fill("9")
    await page.getByRole("button", { name: "Refresh item price and charges", exact: true }).click()
    await expect(page.getByLabel("Item charge percentage", { exact: true })).toHaveValue("8")
    await page.getByRole("button", { name: "Remove item charge", exact: true }).click()
    await expect(page.getByLabel("Item charge percentage", { exact: true })).toHaveCount(0)
    await page.getByRole("button", { name: "Refresh item price and charges", exact: true }).click()
    await expect(page.getByLabel("Item charge percentage", { exact: true })).toHaveValue("8")
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath("quotation-charge-mobile.png"), fullPage: true })
    await page.setViewportSize({ width: 1280, height: 900 })
    await page.screenshot({ path: testInfo.outputPath("quotation-charge-desktop.png"), fullPage: true })
    await page.getByRole("button", { name: "Save document", exact: true }).click()
    await expect(page).toHaveURL(/\/crm\/quotations\/(?!new)[^/]+$/)
    const quoteId = page.url().split("/").pop()!
    const quote = await json(context, `/api/crm/quotations/${quoteId}`)
    expect(quote.snapshot.calculation.consideration).toBe("1080.00")
    expect(quote.snapshot.calculation.charges[0]).toMatchObject({ basis: "LINE", amount: "80.00" })
    const saved = await json(context, `/api/catalog/items/${itemId}`)
    await json(context, `/api/catalog/items/${itemId}`, 200, "PUT", { code: saved.code, name: saved.name, kind: saved.kind, unit: saved.unit, price: "2000", currency: "INR", availability: "AVAILABLE", description: "", archived: false, extensionKey: null, version: saved.version, charges: [{ ...saved.charges[0], value: "10" }] })
    expect((await json(context, `/api/crm/quotations/${quoteId}`)).snapshot).toEqual(quote.snapshot)
    const pdf = await context.request.get(`/api/crm/quotations/${quoteId}/pdf?revision=1`)
    expect(pdf.status()).toBe(200)
    await (await import("node:fs/promises")).writeFile(testInfo.outputPath("item-charge-quotation.pdf"), await pdf.body())
    expect(errors).toEqual([])
  } finally { await context.close(); await f.db.end() }
})
