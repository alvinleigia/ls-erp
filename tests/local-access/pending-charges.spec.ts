import { test, expect } from '@playwright/test'
import { seed, login, json } from './fixtures'
import { emptyQuotationContent } from '../../modules/sales-documents/quotation-validation'

test('collect known amounts, then confirm pending extras on desktop and mobile without changing the agreement', async ({ browser }) => {
  test.setTimeout(180000)
  const f = await seed(), { context, page } = await login(browser, f.origin, f.users.admin.email)
  try {
    page.setDefaultTimeout(20000)
    await f.db.query('INSERT INTO "TenantModule" ("tenantId",key,allowed,enabled,"updatedAt") VALUES ($1,\'salesOrders\',true,true,now()),($1,\'receivables\',true,true,now())', [f.slug])
    const contact = await json(context, '/api/crm/contacts', 201, 'POST', { name: 'QA pending fee customer' })
    const pipeline = await json(context, '/api/crm/pipelines', 201, 'POST', { name: 'QA fee sales', stages: [{ name: 'Open', kind: 'OPEN', probability: 10, color: '#123456' }, { name: 'Won', kind: 'WON', probability: 100, color: '#00aa00' }, { name: 'Lost', kind: 'LOST', probability: 0, color: '#aa0000' }] })
    const deal = await json(context, '/api/crm/opportunities', 201, 'POST', { title: 'QA pending extras', contactId: contact.id, assignedUserId: f.users.admin.id, pipelineId: pipeline.id, stageId: pipeline.stages[0].id, amount: '100', currency: 'INR', expectedCloseOn: '2027-01-01' })
    const content = { ...structuredClone(emptyQuotationContent), supplierName: 'QA Shared Industries', currency: 'INR', lines: [{ description: 'Service', quantity: '1', unit: 'each', rate: '100' }], charges: ['Maintenance', 'Documentation'].map(label => ({ label, kind: 'TBD', value: '0', basis: 'BASE', included: false, due: 'Subject to agreement', group: '' })) }
    const quote = await json(context, `/api/crm/opportunities/${deal.id}/quotations`, 201, 'POST', { content })
    const order = await json(context, '/api/sales-orders', 200, 'POST', { quotationId: quote.id, revision: 1, orderedOn: '2026-01-01' })
    await json(context, `/api/sales-orders/${order.id}`, 200, 'PATCH', { action: 'confirm', version: 1 })
    const endpoint = `/api/sales-orders/${order.id}/receivables`
    await page.goto(`/sales-orders/${order.id}`)
    await page.getByRole('tab', { name: 'Payments', exact: true }).click()
    const charges = page.getByLabel('Unpriced extras', { exact: true })
    await expect(charges).toContainText('Charges to be confirmed (2)')
    await expect(charges.getByRole('button')).toHaveCount(0)
    await page.getByRole('button', { name: 'Open receivables', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm schedule', exact: true }).click()
    await expect(charges.getByRole('button')).toHaveCount(2)
    await page.getByRole('button', { name: 'Record payment', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Amount (INR)', { exact: true }).fill('30')
    await dialog.getByLabel('Payment date', { exact: true }).fill('2026-01-01')
    await dialog.getByLabel('Payment reference', { exact: true }).fill('QA-KNOWN-PAYMENT')
    await dialog.getByRole('button', { name: 'Save payment', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await charges.getByRole('button', { name: 'Confirm amount for Maintenance', exact: true }).click()
    await dialog.getByLabel('Confirmed amount (INR)', { exact: true }).fill('25.50')
    await dialog.getByLabel('Due date (optional)', { exact: true }).fill('2026-12-01')
    await dialog.getByLabel('Confirmation reason / customer agreement reference', { exact: true }).fill('QA customer agreed maintenance charge')
    await page.screenshot({ path: test.info().outputPath('charge-confirmation-desktop.png'), fullPage: true, animations: 'disabled' })
    await dialog.getByRole('button', { name: 'Confirm charge', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    let state = await json(context, endpoint)
    expect(state.account.total).toBe('125.5'); expect(state.paid).toBe('30'); expect(state.outstanding).toBe('95.5')
    expect(state.lines.map((row: { amount: string }) => row.amount)).toEqual(['100', '25.5'])
    await page.setViewportSize({ width: 390, height: 844 })
    await charges.getByRole('button', { name: 'Confirm amount for Documentation', exact: true }).click()
    await dialog.getByLabel('Confirmed amount (INR)', { exact: true }).fill('0')
    await dialog.getByLabel('Confirmation reason / customer agreement reference', { exact: true }).fill('QA no documentation charge is due')
    await page.screenshot({ path: test.info().outputPath('charge-confirmation-mobile.png'), fullPage: true, animations: 'disabled' })
    await dialog.getByRole('button', { name: 'Confirm charge', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(charges).toContainText('all confirmed')
    await expect(charges).toContainText('no charge due')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.reload()
    await expect(charges).toContainText('QA customer agreed maintenance charge')
    state = await json(context, endpoint)
    expect(state.chargeConfirmations).toHaveLength(2); expect(state.account.total).toBe('125.5'); expect(state.account.version).toBe(4)
    expect((await json(context, `/api/crm/quotations/${quote.id}`)).snapshot.content).toMatchObject(content)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await charges.scrollIntoViewIfNeeded()
    await page.screenshot({ path: test.info().outputPath('charges-confirmed-desktop.png'), fullPage: true, animations: 'disabled' })
  } finally { await context.close(); await f.db.end() }
})
