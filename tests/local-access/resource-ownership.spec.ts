import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"

test("ownership guidance distinguishes shared definitions, source offices and unsaved scope limits", async ({ browser }) => {
  test.setTimeout(120_000)
  const f = await seed(), admin = await login(browser, f.origin, f.users.admin.email)
  const writes: string[] = []
  admin.page.on("request", request => { if (!["GET", "HEAD"].includes(request.method())) writes.push(new URL(request.url()).pathname) })
  try {
    const original = await json(admin.context, `/api/access/users/${f.users.staff.id}`)
    const roles = await json(admin.context, "/api/access/roles")
    await admin.page.goto("/settings/roles")
    await admin.page.getByRole("button", { name: "New profile", exact: true }).click()
    await admin.page.getByRole("button", { name: "Profile module", exact: true }).click()
    await admin.page.getByRole("menuitemradio", { name: "Inventory", exact: true }).click()
    await expect(admin.page.getByRole("menu")).toHaveCount(0)
    await admin.page.getByRole("button", { name: "Copy template", exact: true }).click()
    await admin.page.getByRole("menuitemradio", { name: "Inventory Viewer", exact: true }).click()
    const products = admin.page.getByRole("row").filter({ has: admin.page.getByRole("checkbox", { name: "Inventory products and stock: read", exact: true }) })
    await expect(products).toContainText("Product definitions are shared. Stock, costs and reorder settings are limited to permitted offices")
    await expect(admin.page.getByRole("checkbox", { name: "Inventory products and stock: read", exact: true })).toBeChecked()
    await expect(admin.page.getByRole("checkbox", { name: "Inventory products and stock: edit", exact: true })).not.toBeChecked()
    await products.scrollIntoViewIfNeeded()
    expect((await products.locator("th").first().boundingBox())?.width).toBeGreaterThanOrEqual(240)
    expect(await admin.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await admin.page.screenshot({ path: "test-results/local-access/resource-contract-profile.png", fullPage: true, animations: "disabled" })
    await admin.page.getByRole("button", { name: "Cancel", exact: true }).click()
    await admin.page.getByRole("button", { name: "Discard changes", exact: true }).click()
    await expect(admin.page.getByRole("dialog")).toHaveCount(0)
    await admin.page.getByRole("button", { name: "Assign profiles", exact: true }).click()
    await admin.page.getByLabel("User", { exact: true }).click()
    await admin.page.getByRole("option", { name: "Access staff", exact: true }).click()
    const section = (name: string) => admin.page.locator("details").filter({ has: admin.page.locator("summary").filter({ hasText: new RegExp("^" + name + "$", "i") }) })
    await section("Inventory products and stock").locator("summary").click()
    await expect(section("Inventory products and stock")).toContainText("Product definitions are shared.")
    await admin.page.getByRole("button", { name: "Inventory products and stock: read", exact: true }).click()
    await admin.page.getByRole("menuitemradio", { name: "All accessible records", exact: true }).click()
    await expect(admin.page.getByRole("menu")).toHaveCount(0)
    await expect(admin.page.getByRole("button", { name: "Inventory products and stock: read", exact: true })).toHaveText("All accessible records")
    await section("Quotations").locator("summary").click()
    await expect(section("Quotations")).toContainText("Linked records retain their source access and office")
    await section("Quotations").locator("summary").click()
    await admin.page.setViewportSize({ width: 390, height: 844 })
    await section("Inventory products and stock").scrollIntoViewIfNeeded()
    expect(await admin.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(admin.page.getByRole("button", { name: "Save changes", exact: true })).toBeVisible()
    await admin.page.screenshot({ path: "test-results/local-access/resource-contract-limits-mobile.png", fullPage: true, animations: "disabled" })
    await admin.page.getByRole("button", { name: "Cancel", exact: true }).click()
    await admin.page.getByRole("button", { name: "Discard changes", exact: true }).click()
    await expect(admin.page.getByRole("dialog")).toHaveCount(0)
    const unchanged = await json(admin.context, `/api/access/users/${f.users.staff.id}`)
    expect(unchanged.accessPolicy).toEqual(original.accessPolicy)
    expect(unchanged.accessAssignments).toEqual(original.accessAssignments)
    expect((await json(admin.context, "/api/access/roles")).total).toBe(roles.total)
    await admin.page.goto("/settings/companies")
    await expect(admin.page.getByText("This directory defines your business structure. Office membership, record permissions and employee workplace assignments are configured separately.", { exact: true })).toBeVisible()
    expect(writes).toEqual([])
  } finally { await admin.context.close(); await f.db.end() }
})
