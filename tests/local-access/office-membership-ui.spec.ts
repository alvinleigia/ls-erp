test("membership controls are admin-only and clear the draft when administrative authority is revoked", async ({ browser }) => {
  test.setTimeout(120_000)
  const f = await seed(), admin = await login(browser,f.origin,f.users.admin.email)
  let manager: Awaited<ReturnType<typeof login>> | undefined
  try {
    manager = await login(browser,f.origin,f.users.manager.email)
    await manager.page.goto(`/users/${f.users.staff.id}`)
    await expect(manager.page.getByRole("button",{name:"Office access",exact:true})).toHaveCount(0)
    await json(manager.context,`/api/access/users/${f.users.staff.id}/offices/creation-choices`,403,"POST",{officeIds:[],companies:[]})
    await admin.page.goto(`/users/${f.users.staff.id}`);await open(admin.page)
    const office=(await json(admin.context,"/api/offices")).items[0]
    await pick(admin.page,"Add specific office",office.name)
    await expect(admin.page.getByRole("button",{name:"Save office access",exact:true})).toBeEnabled()
    await f.db.query('UPDATE "User" SET role=\'MANAGER\' WHERE id=$1',[f.users.admin.id])
    await admin.page.getByRole("button",{name:"Save office access",exact:true}).click()
    await expect(admin.page.getByRole("alert")).toContainText("Office membership access is not permitted")
    await expect(admin.page.getByLabel("Add specific office",{exact:true})).toHaveCount(0)
    await expect(admin.page.getByRole("button",{name:"Save office access",exact:true})).toHaveCount(0)
    expect((await f.db.query('SELECT count(*)::int n FROM "BusinessOfficePolicy" WHERE "tenantId"=$1 AND "userId"=$2',[f.slug,f.users.staff.id])).rows[0].n).toBe(0)
  } finally { await manager?.context.close();await admin.context.close();await f.db.end() }
})
