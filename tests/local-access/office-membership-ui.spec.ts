import { test, expect, type Page } from "@playwright/test"
import { seed, login, json } from "./fixtures"

async function pick(page: Page, label: string, name: string) {
  await page.getByRole("combobox", { name: label, exact: true }).click()
  await page.getByPlaceholder("Type to search...").fill(name)
  await page.getByRole("option", { name: new RegExp(name) }).click()
  await expect(page.getByRole("listbox")).toHaveCount(0)
}
async function open(page: Page) {
  await page.getByRole("button", { name: "Office access", exact: true }).click()
  await expect(page.getByLabel("Add specific office", { exact: true })).toBeVisible()
}

