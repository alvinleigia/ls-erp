import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"

test("record sharing controls work on desktop and mobile and keep ordinary manager and staff views separate", async ({ browser }, info) => {
  test.setTimeout(150_000)
  const fixture = await seed(), admin = await login(browser, fixture.origin, fixture.users.admin.email)
  const manager = await login(browser, fixture.origin, fixture.users.manager.email), staff = await login(browser, fixture.origin, fixture.users.staff.email)
  try {
    const contact = await json(admin.context, "/api/crm/contacts", 201, "POST", { name: "Sharing test customer" })
    const lead = await json(admin.context, "/api/crm/enquiries", 201, "POST", { title: "Confidential sharing check", contactId: contact.id, assignedUserId: fixture.users.admin.id })
    await admin.page.goto(`/crm/enquiries/${lead.id}`)
    await admin.page.getByRole("button", { name: "Sharing", exact: true }).click()
    const dialog = admin.page.getByRole("dialog")
    await expect(dialog.getByRole("heading", { name: "Record sharing", exact: true })).toBeVisible()
    await dialog.getByLabel("Visibility", { exact: true }).click()
    await admin.page.getByRole("menuitemradio", { name: "Restricted access", exact: true }).click()
    await dialog.getByLabel("User", { exact: true }).click()
    await admin.page.getByRole("option", { name: "Access staff", exact: true }).click()
    await dialog.getByRole("button", { name: "Add recipient", exact: true }).click()
    await expect(dialog.getByRole("list", { name: "Sharing recipients" })).toContainText("Access staff")
    await admin.page.screenshot({ path: info.outputPath("sharing-desktop.png"), fullPage: true, animations: "disabled" })
    await admin.page.setViewportSize({ width: 390, height: 844 })
    await expect(dialog.getByRole("button", { name: "Save sharing", exact: true })).toBeVisible()
    expect(await admin.page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await admin.page.screenshot({ path: info.outputPath("sharing-mobile.png"), fullPage: true, animations: "disabled" })
    await dialog.getByRole("button", { name: "Save sharing", exact: true }).click()
    await expect(admin.page.getByRole("dialog")).toHaveCount(0)
    const policy = await json(admin.context, `/api/access/records/enquiries/${lead.id}`)
    expect(policy.restricted).toBe(true); expect(policy.grants[0].level).toBe("READ")
    await json(manager.context, `/api/crm/enquiries/${lead.id}`, 404)
    await manager.page.goto(`/crm/enquiries/${lead.id}`)
    await expect(manager.page.getByRole("heading", { name: "Confidential sharing check", exact: true })).toHaveCount(0)
    await staff.page.goto(`/crm/enquiries/${lead.id}`)
    await expect(staff.page.getByRole("heading", { name: "Confidential sharing check", exact: true })).toBeVisible()
    await expect(staff.page.getByRole("button", { name: /^Edit/ })).toHaveCount(0)
    await expect(staff.page.getByRole("link", { name: "Convert to opportunity", exact: true })).toHaveCount(0)
    await expect(staff.page.getByRole("button", { name: "Sharing", exact: true })).toHaveCount(0)
    await staff.page.screenshot({ path: info.outputPath("sharing-readonly.png"), fullPage: true, animations: "disabled" })
    await json(staff.context, `/api/access/records/enquiries/${lead.id}`, 403)
    await json(admin.context, `/api/access/records/enquiries/${lead.id}`, 200, "PATCH", { version: policy.version, restricted: true, grants: [] })
    await json(staff.context, `/api/crm/enquiries/${lead.id}`, 404)
    await staff.page.reload()
    await expect(staff.page.getByRole("heading", { name: "Confidential sharing check", exact: true })).toHaveCount(0)
  } finally { await staff.context.close(); await manager.context.close(); await admin.context.close(); await fixture.db.end() }
})
