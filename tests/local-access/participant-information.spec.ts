import { test, expect } from "@playwright/test"
import { seed, login, json, assignProfiles } from "./fixtures"
import { emptyQuotationContent } from "../../modules/sales-documents/quotation-validation"
import { emptyCorrespondence } from "../../platform/participants/information"

test.use({ actionTimeout: 15_000 })
async function fixture(context: Awaited<ReturnType<typeof login>>["context"], userId: string) {
  const person = await json(context, "/api/crm/contacts", 201, "POST", { name: "QA Buyer" })
  const pipeline = await json(context, "/api/crm/pipelines", 201, "POST", { name: "Customer detail checks", stages: [{ name: "Open", kind: "OPEN", probability: 10, color: "#123456" }, { name: "Won", kind: "WON", probability: 100, color: "#00aa00" }, { name: "Lost", kind: "LOST", probability: 0, color: "#aa0000" }] })
  const deal = await json(context, "/api/crm/opportunities", 201, "POST", { title: "Customer detail transaction", contactId: person.id, assignedUserId: userId, pipelineId: pipeline.id, stageId: pipeline.stages[0].id, amount: "100", currency: "INR", expectedCloseOn: "2027-01-01" })
  return { person, deal }
}
const content = () => ({ ...structuredClone(emptyQuotationContent), title: "Customer detail agreement", supplierName: "QA Generic Industries", currency: "INR", lines: [{ description: "Shared service", quantity: "1", unit: "hour", rate: "100" }] })

test("generic correspondence, scoped impact publication, confirmation requirements and frozen order details", async ({ browser }) => {
  test.setTimeout(180_000)
  const f=await seed(),admin=await login(browser,f.origin,f.users.admin.email),{page,context}=admin
  try{
    await f.db.query('UPDATE "TenantModule" SET enabled=false WHERE "tenantId"=$1 AND key=\'realEstate\'',[f.slug])
    await f.db.query('INSERT INTO "TenantModule" ("tenantId",key,allowed,enabled,"updatedAt") VALUES ($1,\'salesOrders\',true,true,now())',[f.slug])
    const {person,deal}=await fixture(context,f.users.admin.id),endpoint=`/api/crm/opportunities/${deal.id}/information`
    const quote=await json(context,`/api/crm/opportunities/${deal.id}/quotations`,201,"POST",{content:content()})
    const order=await json(context,"/api/sales-orders",200,"POST",{quotationId:quote.id,revision:1})
    await page.goto("/settings/customer-details")
    await page.getByLabel("Form title",{exact:true}).fill("")
    await page.getByRole("button",{name:"Preview impact",exact:true}).click()
    await expect(page.getByRole("alert").filter({hasText:"Enter a form title"})).toBeVisible()
    await page.getByLabel("Form title",{exact:true}).fill("Customer correspondence")
    await page.getByLabel("Label for city",{exact:true}).fill("Town")
    await page.getByLabel("Require city for Main customer",{exact:true}).check()
    await expect(page.getByRole("button",{name:"Publish requirements",exact:true})).toBeDisabled()
    await page.getByRole("button",{name:"Preview impact",exact:true}).click()
    await expect(page.getByText(/1 accessible draft orders checked; 1 would need additional details/)).toBeVisible()
    await page.screenshot({path:test.info().outputPath("customer-requirements-desktop.png"),fullPage:true,animations:"disabled"})
    await page.getByRole("button",{name:"Publish requirements",exact:true}).click()
    await expect.poll(async()=>(await json(context,"/api/participant-settings")).version).toBe(1)
    await page.goto(`/sales-orders/${order.id}`)
    await page.getByRole("button",{name:"Confirm sales order",exact:true}).click()
    await page.getByRole("button",{name:"Confirm agreement",exact:true}).click()
    await expect(page.getByRole("dialog").getByRole("alert")).toContainText("QA Buyer: Town")
    await page.goto(`/crm/opportunities/${deal.id}`)
    await page.getByRole("tab",{name:"Customer details",exact:true}).click()
    await expect(page.getByRole("heading",{name:"Customer correspondence",exact:true})).toBeVisible()
    await page.getByRole("button",{name:"Edit customer details",exact:true}).click()
    const dialog=page.getByRole("dialog",{name:"Edit customer details",exact:true})
    await dialog.getByLabel("Town for QA Buyer",{exact:true}).fill("Pune")
    await dialog.getByLabel("Email for QA Buyer",{exact:true}).fill("typo")
    await dialog.getByRole("button",{name:"Save customer details",exact:true}).click()
    await expect(dialog.getByRole("alert")).toContainText("highlighted")
    await dialog.getByLabel("Email for QA Buyer",{exact:true}).fill(" BUYER@EXAMPLE.TEST ")
    await expect(dialog.getByText("Invalid email address",{exact:true})).toHaveCount(0)
    await page.setViewportSize({width:390,height:844})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await expect(dialog.getByRole("button",{name:"Save customer details",exact:true})).toBeInViewport()
    await page.screenshot({path:test.info().outputPath("customer-details-mobile-edit.png"),fullPage:true,animations:"disabled"})
    await dialog.getByRole("button",{name:"Save customer details",exact:true}).click()
    await expect(dialog).toHaveCount(0)
    const accepted=await json(context,endpoint)
    expect(accepted.participants[0].information.email).toBe("buyer@example.test")
    expect((await json(context,`/api/crm/contacts/${person.id}`)).email).toBeNull()
    await json(context,`/api/sales-orders/${order.id}`,409,"PATCH",{action:"confirm",version:1})
    await json(context,`/api/sales-orders/${order.id}`,200,"PATCH",{action:"cancel",version:1,reason:"Use the corrected correspondence revision"})
    await json(context,`/api/crm/quotations/${quote.id}`,200,"PUT",{content:content(),version:1})
    const replacement=await json(context,"/api/sales-orders",200,"POST",{quotationId:quote.id,revision:2})
    await page.goto(`/sales-orders/${replacement.id}`)
    await expect(page.getByText("Pune",{exact:true})).toBeVisible()
    await page.getByRole("button",{name:"Confirm sales order",exact:true}).click()
    await page.getByRole("button",{name:"Confirm agreement",exact:true}).click()
    await expect(page.getByRole("dialog")).toHaveCount(0)
    const fixed=await json(context,`/api/sales-orders/${replacement.id}`)
    expect(fixed.status).toBe("CONFIRMED");expect(fixed.participantAcceptance.configurationVersion).toBe(1)
    expect(fixed.snapshot.participants.presentation.labels.city).toBe("Town")
    await page.screenshot({path:test.info().outputPath("customer-details-mobile-confirmed.png"),fullPage:true,animations:"disabled"})
    // Editing current source details never rewrites the confirmed revision.
    const current=await json(context,endpoint)
    await json(context,endpoint,200,"PUT",{version:current.version,configurationVersion:current.configuration.version,information:{format:1,records:[{party:{kind:"PERSON",id:person.id},values:{...emptyCorrespondence,city:"Mumbai"}}]}})
    expect((await json(context,`/api/sales-orders/${replacement.id}`)).snapshot).toEqual(fixed.snapshot)
  }finally{await context.close();await f.db.end()}
})

test("CIF labels, stale configuration drafts, read-only source access and delegated settings read",async({browser})=>{
  test.setTimeout(120_000)
  const f=await seed(),admin=await login(browser,f.origin,f.users.admin.email)
  let reader:Awaited<ReturnType<typeof login>>|undefined,manager:Awaited<ReturnType<typeof login>>|undefined
  try{
    const {context,page}=admin,{person,deal}=await fixture(context,f.users.staff.id),endpoint=`/api/crm/opportunities/${deal.id}/information`
    await page.goto(`/crm/opportunities/${deal.id}`);await page.getByRole("tab",{name:"Customer details",exact:true}).click()
    await expect(page.getByRole("heading",{name:"Customer information (CIF)",exact:true})).toBeVisible()
    await page.getByRole("button",{name:"Edit customer details",exact:true}).click()
    const dialog=page.getByRole("dialog",{name:"Edit customer details",exact:true})
    await dialog.getByLabel("City for QA Buyer",{exact:true}).fill("Unsaved town")
    const config=await json(context,"/api/participant-settings");config.definition.required.CUSTOMER=["city"]
    const preview=await json(context,"/api/participant-settings/preview",200,"POST",{version:config.version,definition:config.definition})
    await json(context,"/api/participant-settings",200,"PUT",{version:config.version,definition:config.definition,previewHash:preview.previewHash})
    await dialog.getByRole("button",{name:"Save customer details",exact:true}).click()
    await expect(dialog.getByRole("alert")).toContainText("requirements changed")
    await expect(dialog.getByLabel("City for QA Buyer",{exact:true})).toHaveValue("Unsaved town")
    await expect(dialog.getByRole("button",{name:"Save customer details",exact:true})).toBeDisabled()
    await dialog.getByRole("button",{name:"Reload saved details",exact:true}).click()
    await page.getByRole("button",{name:"Discard and reload",exact:true}).click()
    await expect(page.getByRole("dialog")).toHaveCount(0)
    const current=await json(context,endpoint)
    await json(context,endpoint,200,"PUT",{version:current.version,configurationVersion:current.configuration.version,information:{format:1,records:[{party:{kind:"PERSON",id:person.id},values:{...emptyCorrespondence,city:"Saved town"}}]}})
    const role=await json(context,"/api/access/roles",201,"POST",{name:"Source customer detail reader",permissions:["opportunities.read"]})
    await assignProfiles(context,f.users.staff.id,[role.id])
    reader=await login(browser,f.origin,f.users.staff.email)
    await reader.page.goto(`/crm/opportunities/${deal.id}`);await reader.page.getByRole("tab",{name:"Customer details",exact:true}).click()
    await expect(reader.page.getByText("Saved town",{exact:true})).toBeVisible()
    await expect(reader.page.getByRole("button",{name:"Edit customer details",exact:true})).toHaveCount(0)
    await json(reader.context,endpoint,403,"PUT",{version:current.version,configurationVersion:current.configuration.version,information:{format:1,records:[]}})
    await json(reader.context,"/api/participant-settings",403)
    await reader.page.screenshot({path:test.info().outputPath("customer-details-readonly-cif.png"),fullPage:true,animations:"disabled"})
    const delegated=await json(context,"/api/access/roles",201,"POST",{name:"Requirement viewer",moduleKey:"core",permissions:["participantSettings.read","participantSettings.edit"]})
    await assignProfiles(context,f.users.manager.id,[delegated.id])
    manager=await login(browser,f.origin,f.users.manager.email)
    await manager.page.goto("/settings/customer-details")
    await expect(manager.page.getByLabel("Form title",{exact:true})).toBeDisabled()
    await expect(manager.page.getByRole("button",{name:"Publish requirements",exact:true})).toHaveCount(0)
    await json(manager.context,"/api/participant-settings/preview",403,"POST",{version:1,definition:config.definition})
  }finally{await manager?.context.close();await reader?.context.close();await admin.context.close();await f.db.end()}
})
