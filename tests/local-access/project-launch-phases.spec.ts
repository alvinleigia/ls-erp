import { test, expect } from "@playwright/test"
import { seed, login, json } from "./fixtures"

test.use({ actionTimeout: 15_000 })
test("launch phases can be created, edited and assigned independently of the project hierarchy", async ({ browser }) => {
  test.setTimeout(180_000)
  const f = await seed(), admin = await login(browser, f.origin, f.users.admin.email, "Asia/Kolkata")
  const errors: string[] = []; admin.page.on("pageerror", error => errors.push(error.message))
  try {
    await f.db.query('INSERT INTO "TenantModule" ("tenantId",key,allowed,enabled,"updatedAt") VALUES ($1,\'catalog\',true,true,now())', [f.slug])
    const root = await json(admin.context, "/api/real-estate/projects", 201, "POST", { name: "Launch estate", code: "LAUNCH" })
    const child = await json(admin.context, "/api/real-estate/projects", 201, "POST", { name: "Block A", code: "BLOCK-A", parentId: root.id })
    await admin.page.goto(`/crm/projects/${child.id}`)
    await admin.page.getByRole("tab", { name: "Launch phases", exact: true }).click()
    await admin.page.getByRole("button", { name: "New launch phase", exact: true }).click()
    await admin.page.getByLabel("Phase name", { exact: true }).fill("Phase 1")
    await admin.page.getByLabel("Phase code", { exact: true }).fill("PHASE-1")
    await admin.page.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(admin.page.getByRole("dialog")).toHaveCount(0)
    await expect(admin.page.getByText("Planned", { exact: true })).toBeVisible()
    const phases = await json(admin.context, `/api/real-estate/projects/${child.id}/launch-phases`)
    expect(phases.projectId).toBe(root.id)
    const categories = await json(admin.context, "/api/real-estate/choices/property-categories")
    const item = await json(admin.context, "/api/catalog/items", 201, "POST", { code: "LAUNCH-UNIT", name: "Launch unit", kind: "UNIT", unit: "plot", price: "1000", currency: "INR", extensionKey: "realEstate", extension: { projectId: child.id, categoryId: categories.items[0].id, launchPhaseId: phases.items[0].id } })
    expect((await json(admin.context, `/api/catalog/items/${item.id}`)).reservationBlockedReason).toMatch(/not open/)
    await admin.page.getByRole("button", { name: "Edit Phase 1", exact: true }).click()
    await admin.page.getByLabel("Booking status", { exact: true }).click()
    await admin.page.getByRole("menuitemradio", { name: "Open", exact: true }).click()
    await admin.page.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(admin.page.getByRole("dialog")).toHaveCount(0)
    await expect(admin.page.getByText("Open", { exact: true })).toBeVisible()
    expect((await json(admin.context, `/api/catalog/items/${item.id}`)).reservationBlockedReason).toBeNull()
    await admin.page.screenshot({ path: "test-results/project-launch-phases-desktop.png", fullPage: true })
    await admin.page.setViewportSize({ width: 390, height: 844 })
    expect(await admin.page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await admin.page.screenshot({ path: "test-results/project-launch-phases-mobile.png", fullPage: true })
    await admin.page.getByRole("button", { name: "Edit Phase 1", exact: true }).click()
    await admin.page.getByLabel("Opening date and time (optional)", { exact: true }).fill("2027-12-01T09:30")
    await admin.page.getByRole("button", { name: "Save changes", exact: true }).click()
    await expect(admin.page.getByRole("dialog")).toHaveCount(0)
    const saved = await json(admin.context, `/api/real-estate/projects/${root.id}/launch-phases`)
    expect(saved.items[0].opensAt).toBe("2027-12-01T04:00:00.000Z")
    expect((await json(admin.context, `/api/catalog/items/${item.id}`)).reservationBlockedReason).toMatch(/not open/)
    await admin.page.goto(`/catalog/${item.id}`)
    await admin.page.getByRole("tab", { name: "Property unit", exact: true }).click()
    await expect(admin.page.getByText("Phase 1", { exact: true })).toBeVisible()
    expect(errors).toEqual([])
  } finally { await admin.context.close(); await f.db.end() }
})
