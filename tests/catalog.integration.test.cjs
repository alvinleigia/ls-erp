test('quotation item validation rejects forged, stale, unavailable and wrong-currency selections',async()=>{
  const payload=unit(),item=await service.save(payload), valid=content(item)
  const bad=[{...valid,lines:[{...valid.lines[0],catalogItemId:'missing'}]}, {...valid,currency:'USD'}, {...valid,lines:[{...valid.lines[0],quantity:'2'}]}, {...valid,lines:[valid.lines[0],valid.lines[0]]}]
  for(const data of bad) await assert.rejects(crm.saveQuotation(deal.id,{content:data}))
  await service.save({...payload,name:'Changed',version:item.version},item.id)
  await assert.rejects(crm.saveQuotation(deal.id,{content:valid}),status(409))
  const changed=await service.get(item.id)
  await service.save({...payload,availability:'SOLD',version:changed.version},item.id)
  await assert.rejects(crm.saveQuotation(deal.id,{content:content({...changed,version:changed.version+1})}),status(409))
  assert.throws(()=>crm.saveQuotationTemplate({name:'Invalid template',content:valid}),status(400))
})
