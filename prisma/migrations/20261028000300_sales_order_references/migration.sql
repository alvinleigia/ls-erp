CREATE FUNCTION app.assign_sales_order_reference() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public SET row_security=off AS $$
DECLARE n integer; today date;
BEGIN
 IF TG_OP='UPDATE' THEN
  IF NEW.reference IS DISTINCT FROM OLD.reference OR NEW."orderedOn" IS DISTINCT FROM OLD."orderedOn" THEN
   RAISE EXCEPTION 'Order reference and date are immutable' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
 END IF;
 IF app.tenant_match(NEW."tenantId") IS NOT TRUE THEN RAISE EXCEPTION 'Tenant context required' USING ERRCODE='42501'; END IF;
 IF NEW.reference IS NOT NULL THEN RAISE EXCEPTION 'Order references are generated by the system' USING ERRCODE='23514'; END IF;
 SELECT (clock_timestamp() AT TIME ZONE coalesce((SELECT "timeZone" FROM public."AppSetting" WHERE "tenantId"=NEW."tenantId"),'UTC'))::date INTO today;
 NEW."orderedOn":=coalesce(NEW."orderedOn",today);
 IF NEW."orderedOn">today OR NEW."orderedOn"<DATE '0001-01-01' THEN RAISE EXCEPTION 'Choose an order date on or before today' USING ERRCODE='23514'; END IF;
 INSERT INTO public."SalesOrderSequence"("tenantId",value) VALUES(NEW."tenantId",1)
 ON CONFLICT("tenantId") DO UPDATE SET value="SalesOrderSequence".value+1 RETURNING value INTO n;
 NEW.reference:='SO-'||lpad(n::text,greatest(6,length(n::text)),'0');
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION app.assign_sales_order_reference() FROM PUBLIC;
CREATE TRIGGER order_reference BEFORE INSERT OR UPDATE ON "SalesOrder" FOR EACH ROW EXECUTE FUNCTION app.assign_sales_order_reference();

-- Prior orders keep NULL metadata. Existing order/source/security guards are
-- unchanged; their comparison already makes all other saved facts immutable.
COMMIT;
